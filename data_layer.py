"""
Data layer: loading, validating and writing complaints, repair events and
escalations.

Real vs simulated data
----------------------
* data/complaints.csv            REAL. 48 complaints from the 10 Oct 2026 Kandanchavadi
                                 field survey, plus anything citizens submit later.
* data/simulated/*.csv           SIMULATED demo history (repair jobs, follow-up
                                 complaints, resolution times) generated by
                                 tools/generate_simulated_history.py. It exists only so the
                                 accountability, repair-risk and resolution-time features
                                 can be demonstrated. It is always labelled as simulated.
* data/intervention_events.csv   If a REAL repair-history file is ever placed here, it
                                 automatically replaces the simulated one (see
                                 analytics_sources()). No code change is needed.
"""
