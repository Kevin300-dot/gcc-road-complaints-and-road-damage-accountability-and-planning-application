# A new report is linked to an existing road if an existing report is this close.
SEGMENT_ASSIGN_M = 80.0
# Reports this close to a new one (any damage type) are shown to the citizen as "already reported nearby".
NEARBY_REPORT_M = 30.0

MAX_PHOTO_BYTES = 5 * 1024 * 1024
ALLOWED_PHOTO_EXT = {".jpg", ".jpeg", ".png"}

_write_lock = threading.RLock()
_cache = {}


# ---------------------------------------------------------------- helpers

def haversine_m(lat1, lon1, lat2, lon2) -> float:
    r = 6371000.0
    dlat = radians(lat2 - lat1)
    dlon = radians(lon2 - lon1)
    a = sin(dlat / 2) ** 2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(dlon / 2) ** 2
    return r * 2 * atan2(sqrt(a), sqrt(1 - a))


def _ensure_dirs():
    os.makedirs(DATA_DIR, exist_ok=True)
    os.makedirs(UPLOAD_DIR, exist_ok=True)


def _atomic_write_csv(df: pd.DataFrame, path: str):
    """Write to a temp file then rename, so a crash can never leave half a CSV."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(suffix=".csv", dir=os.path.dirname(path))
    os.close(fd)
    try:
        df.to_csv(tmp, index=False)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)
    _cache.pop(path, None)


def _mtime(path):
    return os.path.getmtime(path) if os.path.exists(path) else None


def _cached(path, loader):
    mtime = _mtime(path)
    hit = _cache.get(path)
    if hit and hit["mtime"] == mtime and mtime is not None:
        return hit["df"].copy()
    df = loader()
    _cache[path] = {"mtime": mtime, "df": df}
    return df.copy()


def data_version():
    """Changes whenever any data file changes; used by the backend to invalidate caches."""
    return tuple(_mtime(p) for p in (COMPLAINTS_PATH, EVENTS_PATH, SIM_COMPLAINTS_PATH))


# ---------------------------------------------------------------- loading

def _read_complaints_file(path: str) -> pd.DataFrame:
    if not os.path.exists(path):
        df = pd.DataFrame(columns=COMPLAINT_COLUMNS)
    else:
        df = pd.read_csv(path)
    for col in COMPLAINT_COLUMNS:
        if col not in df.columns:
            df[col] = pd.NA
    df["submission_channel"] = df["submission_channel"].fillna("legacy_record")
    df["area"] = df["area"].fillna(area_config.AREA_NAME)
    df["complaint_date_parsed"] = pd.to_datetime(df["complaint_date"], format="%d-%m-%Y", errors="coerce")
    df["resolution_date_parsed"] = pd.to_datetime(df["resolution_date"], format="%d-%m-%Y", errors="coerce")
    # photo_path may contain a folder prefix (photo_path/xxx.jpg) or an old absolute path
    df["photo_path"] = df["photo_path"].where(df["photo_path"].notna(), None)
    return df


def load_complaints() -> pd.DataFrame:
    """REAL complaints (field survey + citizen submissions)."""
    _ensure_dirs()
    return _cached(COMPLAINTS_PATH, lambda: _read_complaints_file(COMPLAINTS_PATH))


def load_sim_complaints() -> pd.DataFrame:
    """SIMULATED complaint history used only to demo the analytics features."""
    return _cached(SIM_COMPLAINTS_PATH, lambda: _read_complaints_file(SIM_COMPLAINTS_PATH))


def load_events() -> pd.DataFrame:
    """Repair/intervention events. Real file if present, otherwise the simulated one."""
    path = REAL_EVENTS_PATH if os.path.exists(REAL_EVENTS_PATH) else SIM_EVENTS_PATH
    if not os.path.exists(path):
        return pd.DataFrame()

    def _load():
        df = pd.read_csv(path)
        if "data_source" not in df.columns:
            df["data_source"] = "real"
        df["completion_date_parsed"] = pd.to_datetime(df["completion_date"], format="%d-%m-%Y", errors="coerce")
        df["start_date_parsed"] = pd.to_datetime(df["start_date"], format="%d-%m-%Y", errors="coerce")
        return df

    return _cached(path, _load)


def analytics_sources():
    """(complaints, events, label) used by accountability, the repair-risk model and the
    resolution-time estimate. Uses real data when a real repair history exists,
    otherwise the clearly-labelled simulated history."""
    events = load_events()
    if os.path.exists(REAL_EVENTS_PATH):
        return load_complaints(), events, "real"
    return load_sim_complaints(), events, "simulated"


# ---------------------------------------------------------------- roads & locations

def road_table(df: pd.DataFrame) -> pd.DataFrame:
    """One row per road name: centre point and road_segment_id of its most common segment."""
    d = df.dropna(subset=["road_name", "latitude", "longitude"])
    if d.empty:
        return pd.DataFrame(columns=["road_name", "latitude", "longitude", "road_segment_id", "reports"])
    out = (
        d.groupby("road_name")
        .agg(latitude=("latitude", "mean"), longitude=("longitude", "mean"),
             road_segment_id=("road_segment_id", lambda s: s.mode().iloc[0]), reports=("complaint_id", "count"))
        .reset_index()
        .sort_values("road_name")
    )
    return out


def known_locations(df: pd.DataFrame) -> list:
    """Road names a citizen can pick from."""
    return road_table(df)["road_name"].tolist()


def road_coordinates(df: pd.DataFrame, road_name: str):
    """Centre point of a road; falls back to the centre of Kandanchavadi."""
    t = road_table(df)
    m = t[t["road_name"] == road_name]
    if m.empty:
        lat, lon = area_config.centroid()
        return lat, lon
    return float(m.iloc[0]["latitude"]), float(m.iloc[0]["longitude"])


def nearby_reports(df: pd.DataFrame, lat: float, lon: float, radius_m: float = NEARBY_REPORT_M) -> list:
    out = []
    d = df.dropna(subset=["latitude", "longitude"])
    for _, r in d.iterrows():
        dist = haversine_m(lat, lon, r["latitude"], r["longitude"])
        if dist <= radius_m:
            out.append({
                "complaint_id": r["complaint_id"],
                "distance_m": round(dist, 1),
                "damage_type": r["damage_type"],
                "road_name": r["road_name"],
                "status": r["status"],
            })
    return sorted(out, key=lambda x: x["distance_m"])


def _assign_segment(df: pd.DataFrame, lat: float, lon: float):
    """(road_segment_id, road_name) of the nearest existing report within SEGMENT_ASSIGN_M,
    otherwise a new segment on an unnamed road."""
    d = df.dropna(subset=["latitude", "longitude", "road_segment_id"])
    best, best_d = None, None
    for _, r in d.iterrows():
        dist = haversine_m(lat, lon, r["latitude"], r["longitude"])
        if best_d is None or dist < best_d:
            best, best_d = r, dist
    if best is not None and best_d <= SEGMENT_ASSIGN_M:
        return best["road_segment_id"], best["road_name"]
    nums = [int(m.group(1)) for s in df["road_segment_id"].dropna()
            if (m := re.search(r"_(\d+)$", str(s)))]
    return f"KDV_RD_{(max(nums) + 1) if nums else 1:02d}", "Other road"


# ---------------------------------------------------------------- photos

def _validate_photo(photo_bytes: bytes, photo_filename: str) -> str:
    ext = os.path.splitext(photo_filename or "")[1].lower()
    if ext not in ALLOWED_PHOTO_EXT:
        raise ValueError("Photo must be a JPG or PNG file.")
    if len(photo_bytes) > MAX_PHOTO_BYTES:
        raise ValueError("Photo is larger than 5 MB.")
    is_jpeg = photo_bytes[:3] == b"\xff\xd8\xff"
    is_png = photo_bytes[:8] == b"\x89PNG\r\n\x1a\n"
    if not (is_jpeg or is_png):
        raise ValueError("The uploaded file is not a valid JPG or PNG image.")
    return ext


def save_uploaded_photo(file_bytes: bytes, filename: str, complaint_id: str) -> str:
    """Saves into uploads/ and returns the relative path stored in the CSV."""
    ext = _validate_photo(file_bytes, filename)
    _ensure_dirs()
    out_name = f"{complaint_id}{ext}"
    with open(os.path.join(UPLOAD_DIR, out_name), "wb") as f:
        f.write(file_bytes)
    return f"uploads/{out_name}"


def find_photo_file(filename: str):
    """Absolute path of a photo by file name, searching the survey photo folder then uploads/."""
    safe = os.path.basename(filename)
    for folder in (PHOTO_DIR, UPLOAD_DIR):
        candidate = os.path.normpath(os.path.join(folder, safe))
        if candidate.startswith(os.path.normpath(folder) + os.sep) and os.path.isfile(candidate):
            return candidate
    return None


# ---------------------------------------------------------------- complaints

def next_complaint_id(df: pd.DataFrame) -> str:
    nums = []
    for cid in df["complaint_id"].dropna():
        m = re.fullmatch(r"CMP_KDV_(\d+)", str(cid))
        if m:
            nums.append(int(m.group(1)))
    return f"CMP_KDV_{(max(nums) + 1) if nums else 1:03d}"


def submit_complaint(
    location_description: str,
    damage_type_label: str,
    description: str,
    severity_word: str,
    traffic_blocking: bool,
    safety_concern: bool,
    photo_bytes: bytes = None,
    photo_filename: str = None,
    latitude: float = None,
    longitude: float = None,
) -> dict:
    """Adds a citizen complaint. `location_description` is the road name the citizen picked.

    Raises ValueError if the location is outside Kandanchavadi (border roads count as
    inside) or the photo is invalid. Returns the new complaint id plus any existing
    reports within NEARBY_REPORT_M so the citizen can be told it is already known."""
    with _write_lock:
        _ensure_dirs()
        full = _read_complaints_file(COMPLAINTS_PATH)
        existing = full.drop(columns=["complaint_date_parsed", "resolution_date_parsed"])

        road_name_in = (location_description or "").replace(f", {area_config.AREA_NAME}", "").strip()
        if latitude is None or longitude is None:
            latitude, longitude = road_coordinates(full, road_name_in)
        if not area_config.contains(latitude, longitude):
            raise ValueError(f"The selected location is outside {area_config.AREA_NAME}. Please move the pin inside the area.")

        damage_type = LABEL_TO_DAMAGE_TYPE.get(damage_type_label, "Other")
        severity_field = SEVERITY_TO_FIELD.get(severity_word, "Medium")

        complaint_id = next_complaint_id(existing)
        photo_path = ""
        if photo_bytes and photo_filename:
            photo_path = save_uploaded_photo(photo_bytes, photo_filename, complaint_id)

        nearby = nearby_reports(full, latitude, longitude)
        segment_id, road_name = _assign_segment(full, latitude, longitude)
        if road_name == "Other road" and road_name_in and road_name_in in known_locations(full):
            road_name = road_name_in
        now = datetime.now()

        row = {
            "complaint_id": complaint_id,
            "road_segment_id": segment_id,
            "complaint_date": now.strftime("%d-%m-%Y"),
            "complaint_time": now.strftime("%H:%M"),
            "latitude": round(float(latitude), 6),
            "longitude": round(float(longitude), 6),
            "location_description": f"{road_name}, {area_config.AREA_NAME}",
            "complaint_text": (description or "").strip() or "No additional details provided.",
            "language": "English",
            "damage_type": damage_type,
            "severity": severity_field,
            "traffic_impact": "High" if traffic_blocking else "Low",
            "safety_risk": "High" if safety_concern else "Low",
            "vehicle_accident_reported": "No",
            "pedestrian_risk": "Yes" if safety_concern else "No",
            "two_wheeler_risk": "Yes" if safety_concern else "No",
            "emergency_route": "No",
            "status": "Open",
            "assigned_department": "GCC Roads",
            "resolution_date": "",
            "resolution_type": "",
            "photo_path": photo_path,
            "submission_channel": "citizen_app",
            "data_source": "citizen_app",
            "area": area_config.AREA_NAME,
            "road_name": road_name,
            "observed_at": now.strftime("%Y-%m-%d %H:%M:%S"),
        }
        out = pd.concat([existing, pd.DataFrame([row])], ignore_index=True)
        _atomic_write_csv(out, COMPLAINTS_PATH)

    return {
        "complaint_id": complaint_id,
        "road_name": road_name,
        "road_segment_id": segment_id,
        "nearby_reports": nearby,
    }


def get_complaint_status(complaint_id: str):
    df = load_complaints()
    match = df[df["complaint_id"] == complaint_id]
    if match.empty:
        return None
    row = match.iloc[0]
    return {
        "complaint_id": row["complaint_id"],
        "location_description": row["location_description"],
        "damage_type": row["damage_type"],
        "damage_type_label": DAMAGE_TYPE_LABELS.get(row["damage_type"], row["damage_type"]),
        "complaint_date": row["complaint_date"],
        "status": row["status"],
        "resolution_date": row["resolution_date"] if str(row["resolution_date"]).strip() not in ("", "nan", "<NA>") else None,
        "resolution_type": row["resolution_type"] if str(row["resolution_type"]).strip() not in ("", "nan", "<NA>") else None,
    }


def update_complaint_status(complaint_id: str, new_status: str, resolution_type: str = None):
    if new_status not in VALID_STATUSES:
        raise ValueError(f"Status must be one of {VALID_STATUSES}")
    with _write_lock:
        df = pd.read_csv(COMPLAINTS_PATH)
        mask = df["complaint_id"] == complaint_id
        if not mask.any():
            raise KeyError(complaint_id)
        df["resolution_date"] = df["resolution_date"].astype("object")
        df["resolution_type"] = df["resolution_type"].astype("object")
        df.loc[mask, "status"] = new_status
        if new_status == "Resolved":
            existing_date = df.loc[mask, "resolution_date"]
            if existing_date.isna().all() or (existing_date == "").all():
                df.loc[mask, "resolution_date"] = datetime.now().strftime("%d-%m-%Y")
            if resolution_type:
                df.loc[mask, "resolution_type"] = resolution_type
        _atomic_write_csv(df, COMPLAINTS_PATH)


def update_intervention_restoration(event_id: str, restoration_completed: str):
    if restoration_completed not in ("Yes", "No"):
        raise ValueError("restoration_completed must be Yes or No")
    path = REAL_EVENTS_PATH if os.path.exists(REAL_EVENTS_PATH) else SIM_EVENTS_PATH
    with _write_lock:
        df = pd.read_csv(path)
        if not (df["event_id"] == event_id).any():
            raise KeyError(event_id)
        df.loc[df["event_id"] == event_id, "restoration_completed"] = restoration_completed
        _atomic_write_csv(df, path)


# ---------------------------------------------------------------- escalations

def load_escalations() -> pd.DataFrame:
    _ensure_dirs()
    if not os.path.exists(ESCALATIONS_PATH):
        return pd.DataFrame(columns=ESCALATION_COLUMNS)
    return pd.read_csv(ESCALATIONS_PATH)


def save_escalation(cluster_id: str, escalated_to: str, note: str, officer_name: str):
    with _write_lock:
        df = load_escalations()
        row = {
            "cluster_id": cluster_id,
            "escalated_at": datetime.now().strftime("%d-%m-%Y %H:%M"),
            "escalated_to": escalated_to,
            "note": note,
            "officer_name": officer_name or "GCC Officer",
        }
        df = pd.concat([df, pd.DataFrame([row])], ignore_index=True)
        _atomic_write_csv(df, ESCALATIONS_PATH)
