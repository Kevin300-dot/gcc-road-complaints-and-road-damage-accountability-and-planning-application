SIM_COMPLAINTS_PATH = os.path.join(SIM_DIR, "complaints_sim.csv")
ESCALATIONS_PATH = os.path.join(DATA_DIR, "escalations.csv")
EVENTS_PATH = REAL_EVENTS_PATH if os.path.exists(REAL_EVENTS_PATH) else SIM_EVENTS_PATH

